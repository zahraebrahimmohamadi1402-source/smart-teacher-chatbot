# =====================================================
# تشخیص هوشمند منظور دانش‌آموز
# نسخه فعلی بدون API
# =====================================================


def normalize(text):
    """
    یکدست کردن متن
    """

    text = text.strip()

    text = text.replace("ي", "ی")
    text = text.replace("ك", "ک")
    text = text.replace("‌", " ")

    text = text.replace("؟", "")
    text = text.replace(".", "")
    text = text.replace("!", "")
    text = text.replace("،", "")

    return text


def contains_any(text, words):
    """
    بررسی می‌کند آیا یکی از کلمات موردنظر
    در جمله وجود دارد یا نه.
    """

    for word in words:

        if word in text:
            return True

    return False


def classify_intent(text):
    """
    تشخیص منظور دانش‌آموز
    """

    text = normalize(text)

    if not text:
        return "UNCLEAR"


    # =================================================
    # شروع املا
    # =================================================

    if contains_any(
        text,
        [
            "آماده ام",
            "آماده‌ام",
            "حاضرم",
            "شروع کنیم",
            "بریم شروع"
        ]
    ):

        return "START"


    # =================================================
    # تکرار
    # =================================================

    if contains_any(
        text,
        [
            "دوباره",
            "باز بگو",
            "تکرارش",
            "یک بار دیگه",
            "یه بار دیگه",
            "نفهمیدم"
        ]
    ):

        return "REPEAT"


    # =================================================
    # نوشتم
    # =================================================

    if contains_any(
        text,
        [
            "نوشتم",
            "تموم کردم",
            "تمام کردم",
            "کارم تموم",
            "کارم تمام"
        ]
    ):

        return "WROTE"


    # =================================================
    # ننوشتم
    # =================================================

    if contains_any(
        text,
        [
            "ننوشتم",
            "نتونستم بنویسم",
            "نتونستم",
            "نرسیدم بنویسم"
        ]
    ):

        return "DID_NOT_WRITE"


    # =================================================
    # بلد نیستم
    # =================================================

    if contains_any(
        text,
        [
            "بلد نیستم",
            "نمی‌دونم",
            "نمی دونم",
            "نمیدونم"
        ]
    ):

        return "DONT_KNOW"


    # =================================================
    # چجوری بنویسم
    # =================================================

    if contains_any(
        text,
        [
            "چجوری بنویسم",
            "چطور بنویسم",
            "چگونه بنویسم",
            "این رو چجوری بنویسم"
        ]
    ):

        return "HOW_TO_WRITE"


    # =================================================
    # صبر
    # =================================================

    if contains_any(
        text,
        [
            "صبر کن",
            "وایسا",
            "یه لحظه",
            "کمی صبر"
        ]
    ):

        return "WAIT"


    # =================================================
    # آرام‌تر
    # =================================================

    if contains_any(
        text,
        [
            "آرام تر",
            "آرام‌تر",
            "یواش تر",
            "یواش‌تر",
            "کندتر",
            "آهسته"
        ]
    ):

        return "SLOWER"


    # =================================================
    # بعدی
    # =================================================

    if contains_any(
        text,
        [
            "بعدی",
            "برو بعدی",
            "جمله بعدی",
            "یکی دیگه",
            "یکی دیگه رو بگو"
        ]
    ):

        return "NEXT"


    # =================================================
    # تأیید برای رفتن به جمله بعدی
    # =================================================

    if text in [
        "بله",
        "بله بریم",
        "آره",
        "اره",
        "آره بریم",
        "باشه",
        "باشه بریم",
        "حتما",
        "حتماً",
        "بریم"
    ]:

        return "NEXT"


    # =================================================
    # پایان املا
    # =================================================

    if contains_any(
        text,
        [
            "تمام شد",
            "تموم شد",
            "املا تموم",
            "پایان املا",
            "دیگه تمومه"
        ]
    ):

        return "FINISH"


    # =================================================
    # هیچ فرمانی پیدا نشد
    # =================================================

    return "OFF_TOPIC"